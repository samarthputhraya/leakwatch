"""``make reports``: subject report drafts generated from ``reports/metrics/*.json`` (PRD §0, §12).

Every number in the four drafts (``reports/{bdt,dl,pe,st}/REPORT.md``) is read from a metrics
file and named with its source; nothing is typed by hand. A missing metrics file is reported as
missing, with the command that produces it.
"""

