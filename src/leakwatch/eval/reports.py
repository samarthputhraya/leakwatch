def _get(d: Any, *keys: Any) -> Any:
    """Nested lookup that returns None when any level is missing."""
    for k in keys:
        if isinstance(d, dict):
            d = d.get(k)
        elif isinstance(d, list) and isinstance(k, int) and -len(d) <= k < len(d):
            d = d[k]
        else:
            return None
    return d


