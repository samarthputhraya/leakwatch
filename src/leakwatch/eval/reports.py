from leakwatch.common.paths import METRICS_DIR, REPORTS_DIR

MISSING = "_not available — run `{cmd}`_"


def load(name: str) -> dict[str, Any] | None:
    """A metrics file as a dict, or None if it does not exist."""
    path = METRICS_DIR / f"{name}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def num(value: Any, digits: int = 2, pct: bool = False) -> str:
    """Format a number (or say n/a)."""
    if value is None:
        return "n/a"
    if pct:
        return f"{100 * float(value):.{max(digits - 2, 0)}f}%"
    if isinstance(value, int) or (isinstance(value, float) and value.is_integer() and digits == 0):
        return f"{int(value):,}"
    return f"{float(value):,.{digits}f}"


def src(name: str, meta: dict[str, Any] | None) -> str:
    """Source note for a metrics file."""
    commit = (meta or {}).get("meta", {}).get("git_commit", "?")
    return f"`reports/metrics/{name}.json` (code {commit})"


def table(header: list[str], rows: list[list[Any]]) -> str:
    """Markdown table."""
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


